func TestDecodeULCooperationWithEPD7f(t *testing.T) {
	// UE发送的完整消息数据（包含NGAP头部）
	// NAS消息从offset 25开始：7f 00 e1 ...
	fullMessage := []byte{
		0x00, 0x02, 0x00, 0x84, 0x00, 0x26, 0x00, 0x80, 0x84, 0x80, 0x82,
		0x7e, 0x02, 0x94, 0x42, 0x86, 0x51, 0x0a, 0x7e, 0x00, 0xe1, 0x02,
		0x71, 0x00, 0x74, 0x7f, 0x00, 0xe1, 0x02, 0x71, 0x00, 0x6d, 0x01,
		0x00, 0x00, 0x69, 0x03, 0x7b, 0x22, 0x69, 0x6e, 0x74, 0x65, 0x6e,
		0x74, 0x49, 0x64, 0x22, 0x3a, 0x22, 0x65, 0x64, 0x66, 0x63, 0x34,
		0x31, 0x32, 0x39, 0x2d, 0x38, 0x36, 0x32, 0x33, 0x2d, 0x34, 0x36,
		0x63, 0x31, 0x2d, 0x39, 0x31, 0x63, 0x31, 0x2d, 0x33, 0x31, 0x64,
		0x63, 0x38, 0x35, 0x66, 0x62, 0x62, 0x38, 0x37, 0x66, 0x22, 0x2c,
		0x22, 0x69, 0x6e, 0x74, 0x65, 0x6e, 0x74, 0x44, 0x65, 0x73, 0x63,
		0x72, 0x69, 0x70, 0x74, 0x69, 0x6f, 0x6e, 0x22, 0x3a, 0x22, 0x48,
		0x65, 0x6c, 0x6c, 0x6f, 0x22, 0x2c, 0x22, 0x6f, 0x62, 0x6a, 0x65,
		0x63, 0x74, 0x22, 0x3a, 0x22, 0x4e, 0x65, 0x77, 0x4e, 0x41, 0x53,
		0x41, 0x64, 0x61, 0x70, 0x74, 0x65, 0x72, 0x22, 0x7d, 0x00, 0x79,
		0x40, 0x0f, 0x40, 0x00, 0xf1, 0x10, 0x00, 0x00, 0x01, 0x14, 0xd0,
		0x00, 0xf1, 0x10, 0x00, 0x00, 0x01,
	}

	// 提取NAS消息部分（从offset 25开始）
	nasPdu := fullMessage[25:]

	t.Log("=== 测试解析EPD=0x7f的ULCooperation消息 ===")
	t.Logf("完整消息长度: %d 字节", len(fullMessage))
	t.Logf("NAS消息长度: %d 字节", len(nasPdu))
	t.Logf("NAS消息前10字节: %02x %02x %02x %02x %02x %02x %02x %02x %02x %02x",
		nasPdu[0], nasPdu[1], nasPdu[2], nasPdu[3], nasPdu[4],
		nasPdu[5], nasPdu[6], nasPdu[7], nasPdu[8], nasPdu[9])

	// 验证关键字节
	if nasPdu[0] != 0x7f {
		t.Fatalf("❌ EPD不是0x7f，实际是0x%02x", nasPdu[0])
	}
	t.Logf("✓ EPD = 0x%02x", nasPdu[0])

	if nasPdu[1] != 0x00 {
		t.Fatalf("❌ SecurityHeader不是0x00，实际是0x%02x", nasPdu[1])
	}
	t.Logf("✓ SecurityHeader = 0x%02x", nasPdu[1])

	if nasPdu[2] != nas.MsgTypeULCooperation {
		t.Fatalf("❌ MessageType不是ULCooperation(0x%02x)，实际是0x%02x", nas.MsgTypeULCooperation, nasPdu[2])
	}
	t.Logf("✓ MessageType = 0x%02x (ULCooperation)", nasPdu[2])

	// 创建测试UE context
	amfSelf := context.GetSelf()
	ue := amfSelf.NewAmfUe("")
	ue.SecurityContextAvailable = false  // Plain NAS消息

	t.Log("\n=== 使用Decode函数解析 ===")

	// 调用Decode函数（会触发特殊处理）
	msg, integrityProtected, err := nas_security.Decode(ue, context.AccessType3GPPAccess, nasPdu, false)

	if err != nil {
		t.Fatalf("❌ Decode失败: %v", err)
	}
	t.Log("✓ Decode成功")

	if msg == nil {
		t.Fatal("❌ 返回的Message为nil")
	}
	t.Log("✓ Message不为nil")

	if !integrityProtected {
		t.Log("✓ integrityProtected=false (plain NAS)")
	}

	if msg.GmmMessage == nil {
		t.Fatal("❌ GmmMessage为nil")
	}
	t.Log("✓ GmmMessage不为nil")

	if msg.GmmMessage.ULCooperation == nil {
		t.Fatal("❌ ULCooperation为nil")
	}
	t.Log("✓ ULCooperation不为nil")

	ul := msg.GmmMessage.ULCooperation

	// 验证解析结果
	t.Log("\n=== 解析结果验证 ===")
	
	t.Logf("ExtendedProtocolDiscriminator: 0x%02x", ul.ExtendedProtocolDiscriminator.Octet)
	if ul.ExtendedProtocolDiscriminator.Octet != 0x7f {
		t.Errorf("❌ EPD应为0x7f，实际为0x%02x", ul.ExtendedProtocolDiscriminator.Octet)
	} else {
		t.Log("✓ EPD正确")
	}

	t.Logf("SpareHalfOctetAndSecurityHeaderType: 0x%02x", ul.SpareHalfOctetAndSecurityHeaderType.Octet)
	t.Logf("MessageType (field): 0x%02x", ul.MessageType)
	t.Log("\n✓ ULCooperation消息结构检查:")
	t.Logf("ExtendedProtocolDiscriminator: 0x%02x", ul.ExtendedProtocolDiscriminator.Octet)
	t.Logf("SpareHalfOctetAndSecurityHeaderType: 0x%02x", ul.SpareHalfOctetAndSecurityHeaderType.Octet)
	t.Logf("MessageType: 0x%02x", ul.MessageType)
	t.Logf("MessageIdentity: 0x%02x", ul.MessageIdentity)

	if ul.MessageType != nas.MsgTypeULCooperation {
		t.Errorf("❌ MessageType应为0x%02x，实际为0x%02x", nas.MsgTypeULCooperation, ul.MessageType)
	} else {
		t.Log("✓ MessageType正确")
	}

	// 验证IE解析
	t.Log("\n=== IE信息 ===")
	t.Logf("ULApContainer: %v", ul.ULApContainer != nil)
	t.Logf("UnknownIEs数量: %d", len(ul.UnknownIEs))

	for i, ie := range ul.UnknownIEs {
		t.Logf("\nUnknownIE[%d]:", i)
		t.Logf("  IEI: 0x%02x", ie.GetIei())
		t.Logf("  Length: %d", ie.GetLen())
		contents := ie.GetContents()
		if len(contents) > 0 && contents[0] == 0x7b {
			// JSON内容
			t.Logf("  Contents (JSON): %s", string(contents[:min(100, len(contents))]))
		} else if len(contents) > 20 {
			t.Logf("  Contents (Hex前20字节): %02x ...", contents[:20])
		} else {
			t.Logf("  Contents (Hex): %02x", contents)
		}
	}

	t.Log("\n✅ 成功解析EPD=0x7f的ULCooperation消息！")
}

